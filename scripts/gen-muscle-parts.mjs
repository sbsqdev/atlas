// Generates src/data/muscleParts.generated.ts — a map from our MuscleId regions
// to BodyParts3D part IDs, matched by anatomical name within the muscular system.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const atlas = JSON.parse(readFileSync(resolve(here, '../public/models/atlas.json'), 'utf8'));
const muscular = atlas.parts.filter((p) => p.system === 'muscular');

// keyword → our region. Keywords are matched as case-insensitive substrings of
// the part name, but anchored enough to avoid foot/hand collisions.
const RULES = {
  chest: ['pectoralis major', 'pectoralis minor', 'serratus anterior'],
  // BodyParts3D 4.0 has no rectus abdominis mesh; the anterior core is
  // represented by the external oblique wall and the iliopsoas hip flexors.
  abs: ['external oblique', 'psoas major', 'iliacus'],
  obliques: ['external oblique'],
  // Trunk portion of the erector spinae group (neck heads excluded).
  lowerBack: ['iliocostalis lumborum', 'iliocostalis thoracis', 'longissimus thoracis', 'spinalis thoracis', 'interspinalis thoracis', 'quadratus lumborum'],
  // No latissimus dorsi mesh exists; the visible pull muscles are the teres
  // major and the rhomboids.
  lats: ['teres major', 'rhomboid'],
  traps: ['trapezius', 'rhomboid', 'levator scapulae'],
  shoulders: ['deltoid', 'supraspinatus', 'infraspinatus', 'teres major', 'teres minor', 'subscapularis'],
  biceps: ['biceps brachii', 'brachialis', 'coracobrachialis'],
  triceps: ['triceps brachii', 'anconeus'],
  forearms: [
    'brachioradialis', 'flexor carpi', 'extensor carpi', 'pronator teres', 'pronator quadratus',
    'supinator', 'palmaris longus', 'flexor digitorum superficialis', 'flexor digitorum profundus',
    'flexor pollicis longus', 'extensor pollicis', 'extensor indicis', 'extensor digiti minimi',
    'abductor pollicis longus',
  ],
  glutes: ['gluteus maximus', 'gluteus medius', 'gluteus minimus'],
  quads: ['rectus femoris', 'vastus lateralis', 'vastus medialis', 'vastus intermedius'],
  hamstrings: ['biceps femoris', 'semitendinosus', 'semimembranosus'],
  adductors: ['adductor magnus', 'adductor longus', 'adductor brevis', 'adductor minimus', 'gracilis', 'pectineus'],
  abductors: ['gluteus medius', 'gluteus minimus', 'tensor fasciae latae', 'sartorius'],
  calves: ['gastrocnemius', 'soleus', 'plantaris'],
};

const result = {};
const summary = {};
for (const [region, keywords] of Object.entries(RULES)) {
  const matched = muscular.filter((p) => {
    const n = p.name.toLowerCase();
    return keywords.some((k) => n.includes(k));
  });
  result[region] = matched.map((p) => p.id).sort();
  summary[region] = matched.map((p) => p.name);
}

// Report for human review.
for (const [region, names] of Object.entries(summary)) {
  console.log(`\n### ${region} (${names.length})`);
  console.log(names.join(' | '));
}

const header = `// AUTO-GENERATED by scripts/gen-muscle-parts.mjs — do not edit by hand.
// Maps each muscle region (MuscleId) to BodyParts3D part IDs in the muscular
// system, matched by anatomical name. Source: BodyParts3D 4.0 (CC BY 4.0).
import type { MuscleId } from '../types';

export const MUSCLE_PARTS: Record<MuscleId, string[]> = ${JSON.stringify(result, null, 2)} as Record<MuscleId, string[]>;
`;
writeFileSync(resolve(here, '../src/data/muscleParts.generated.ts'), header);
const total = new Set(Object.values(result).flat()).size;
console.log(`\nWROTE src/data/muscleParts.generated.ts — ${total} distinct parts across ${Object.keys(result).length} regions.`);
