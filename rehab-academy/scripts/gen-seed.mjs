// Generates supabase/seed.sql from the TypeScript content files, so the
// database seed and the in-browser demo never drift apart.
// Usage: node --experimental-strip-types scripts/gen-seed.mjs
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = (p) => join(here, '..', 'src', 'data', 'content', p);
const { STRUCTURES } = await import(src('anatomy.ts'));
const { SIMULATIONS } = await import(src('simulations.ts'));
const { PATIENTS } = await import(src('patients.ts'));
const { SEED_COURSES, SEED_MODULES, SEED_LESSONS } = await import(src('courses.ts'));
const { SEED_ASSESSMENTS, SEED_QUESTIONS } = await import(src('assessments.ts'));
const { PLANS } = await import(src('plans.ts'));

// Stable UUIDs derived from the content ids used by the demo.
const uuid = (id) => {
  const h = createHash('md5').update(`rehab-academy:${id}`).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const q = (v) => (v === undefined || v === null ? 'null' : typeof v === 'number' || typeof v === 'boolean' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const j = (v) => (v === undefined ? 'null' : `${q(JSON.stringify(v))}::jsonb`);
const arr = (a) => `array[${(a ?? []).map(q).join(',')}]::text[]`;

const USERS = [
  ['u-super', 'super@demo.example', 'Администратор платформы (демо)', 'super_admin', 'org-platform'],
  ['u-uniadmin', 'uni@demo.example', 'Администратор университета (демо)', 'uni_admin', 'org-uni'],
  ['u-clinicadmin', 'clinic@demo.example', 'Администратор клиники (демо)', 'clinic_admin', 'org-clinic'],
  ['u-instructor', 'instructor@demo.example', 'Преподаватель (демо)', 'instructor', 'org-uni'],
  ['u-student', 'student@demo.example', 'Студент (демо)', 'student', 'org-uni'],
];

const out = [];
const w = (s) => out.push(s);
w(`-- GENERATED by scripts/gen-seed.mjs — do not edit by hand.
-- Demo/staging seed for Rehab Academy. All organizations and people are
-- SYNTHETIC. Never run this against a production database: it creates demo
-- accounts with the shared password "demo1234".
begin;
`);

w('-- Plans (indicative prices, KZT)');
for (const p of PLANS) w(`insert into plans (id, name, price_kzt, per_seat, entitlements) values (${q(p.id)}, ${q(p.name)}, ${q(p.priceKzt)}, ${p.perSeat}, ${arr(p.entitlements)}) on conflict (id) do nothing;`);

w('\n-- Demo organizations');
for (const [id, name, type, city] of [
  ['org-platform', 'Rehab Academy', 'platform', null],
  ['org-uni', 'Демонстрационный медицинский университет (DEMO)', 'university', 'Алматы'],
  ['org-clinic', 'Демонстрационная клиника реабилитации (DEMO)', 'clinic', 'Астана'],
]) w(`insert into organizations (id, name, type, city, is_demo) values (${q(uuid(id))}, ${q(name)}, ${q(type)}, ${q(city)}, ${id !== 'org-platform'}) on conflict (id) do nothing;`);

w('\n-- Demo auth users (local/staging only). Profiles are created by the on_auth_user_created trigger.');
for (const [id, email, name] of USERS) {
  w(`insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at, confirmation_token, recovery_token, email_change_token_new, email_change)
values ('00000000-0000-0000-0000-000000000000', ${q(uuid(id))}, 'authenticated', 'authenticated', ${q(email)}, crypt('demo1234', gen_salt('bf')), now(), '{"provider":"email","providers":["email"]}', ${j({ full_name: name })}, now(), now(), '', '', '', '') on conflict (id) do nothing;`);
  w(`insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
values (gen_random_uuid(), ${q(uuid(id))}, ${q(uuid(id))}, ${j({ sub: uuid(id), email })}, 'email', now(), now(), now()) on conflict do nothing;`);
}
for (const [id, , , role, org] of USERS) w(`update profiles set role = ${q(role)}, org_id = ${q(uuid(org))}, is_demo = true, consent_at = now() where id = ${q(uuid(id))};`);

w('\n-- Anatomy reference content');
for (const s of STRUCTURES) {
  w(`insert into anatomy_structures (id, name, latin, grp, region, classification, origin, insertion, innervation, function, biomech, notes, "references", has_model, verified) values (${[
    s.id, s.name, s.latin, s.group, s.region, s.classification, s.origin, s.insertion, s.innervation, s.function, s.biomech, s.notes,
  ].map(q).join(', ')}, ${j(s.references)}, ${s.hasModel}, ${s.verified}) on conflict (id) do nothing;`);
}

w('\n-- Courses, modules, lessons');
for (const c of SEED_COURSES) {
  w(`insert into courses (id, title, category, level, description, instructor_id, org_id, duration_min, status, cover, version, is_demo) values (${q(uuid(c.id))}, ${q(c.title)}, ${q(c.category)}, ${q(c.level)}, ${q(c.description)}, ${q(uuid(c.instructorId))}, null, ${c.durationMin}, ${q(c.status)}, ${q(c.cover)}, ${c.version}, true) on conflict (id) do nothing;`);
}
for (const m of SEED_MODULES) w(`insert into course_modules (id, course_id, title, position) values (${q(uuid(m.id))}, ${q(uuid(m.courseId))}, ${q(m.title)}, ${m.order}) on conflict (id) do nothing;`);

w('\n-- Simulations and virtual patients (definitions stored as JSON)');
for (const s of SIMULATIONS) {
  const { id, title, category, difficulty, durationMin, courseId, available, status, ...definition } = s;
  w(`insert into simulations (id, title, category, difficulty, duration_min, course_id, available, status, definition) values (${q(id)}, ${q(title)}, ${q(category)}, ${difficulty}, ${durationMin}, ${courseId ? q(uuid(courseId)) : 'null'}, ${available}, ${q(status)}, ${j(definition)}) on conflict (id) do nothing;`);
}
for (const p of PATIENTS) {
  const { id, title, status, ...definition } = p;
  w(`insert into virtual_patients (id, title, status, definition) values (${q(id)}, ${q(title)}, ${q(status)}, ${j(definition)}) on conflict (id) do nothing;`);
}

w('\n-- Assessments and questions');
for (const a of SEED_ASSESSMENTS) {
  w(`insert into assessments (id, title, course_id, author_id, passing_score, max_attempts, time_limit_min, randomize, feedback, status) values (${q(uuid(a.id))}, ${q(a.title)}, ${q(uuid(a.courseId))}, ${q(uuid(a.authorId))}, ${a.passingScore}, ${a.maxAttempts}, ${a.timeLimitMin}, ${a.randomize}, ${q(a.feedback)}, ${q(a.status)}) on conflict (id) do nothing;`);
}
SEED_QUESTIONS.forEach((x, i) => {
  w(`insert into questions (id, assessment_id, type, prompt, case_text, structure_id, options, pairs, sequence, explanation, points, position) values (${q(uuid(x.id))}, ${q(uuid(x.assessmentId))}, ${q(x.type)}, ${q(x.prompt)}, ${q(x.caseText)}, ${q(x.structureId)}, ${j(x.options)}, ${j(x.pairs)}, ${j(x.sequence)}, ${q(x.explanation)}, ${x.points}, ${i + 1}) on conflict (id) do nothing;`);
});
for (const c of SEED_COURSES.filter((x) => x.finalAssessmentId)) w(`update courses set final_assessment_id = ${q(uuid(c.finalAssessmentId))} where id = ${q(uuid(c.id))};`);

for (const l of SEED_LESSONS) {
  w(`insert into lessons (id, course_id, module_id, title, type, body, video_url, file_url, simulation_id, assessment_id, anatomy_focus, duration_min, position) values (${q(uuid(l.id))}, ${q(uuid(l.courseId))}, ${q(uuid(l.moduleId))}, ${q(l.title)}, ${q(l.type)}, ${q(l.body)}, ${q(l.videoUrl)}, ${q(l.fileUrl)}, ${q(l.simulationId)}, ${l.assessmentId ? q(uuid(l.assessmentId)) : 'null'}, ${arr(l.anatomyFocus)}, ${l.durationMin}, ${l.order}) on conflict (id) do nothing;`);
}

w(`\n-- Manual pilot license for the demo university (no payment is simulated)
insert into subscriptions (org_id, plan_id, status, seats, ends_at, source, activated_by)
values (${q(uuid('org-uni'))}, 'university', 'pilot', 50, now() + interval '90 days', 'manual_pilot', ${q(uuid('u-super'))});

commit;`);

writeFileSync(join(here, '..', 'supabase', 'seed.sql'), out.join('\n') + '\n');
console.log(`seed.sql: ${STRUCTURES.length} structures, ${SEED_COURSES.length} courses, ${SEED_LESSONS.length} lessons, ${SEED_QUESTIONS.length} questions, ${SIMULATIONS.length} simulations`);
