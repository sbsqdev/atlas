/** Splits the title off and puts every numbered clause in its own paragraph. */
function parts(src: string) {
  const [first, ...rest] = src.split('\n');
  return { title: first.replace(/^# /, ''), body: rest.join('\n').replace(/\n(?=\d+\.\d+\.)/g, '\n\n') };
}

